#!/usr/bin/env python3
"""Writes src/unicode_tables.h from the Unicode Character Database and the CodeMirror 5 of the web editor.

usage: tools/unicode_tables.py GraphemeBreakProperty.txt emoji-data.txt EastAsianWidth.txt codemirror.js
The data files come from https://www.unicode.org/Public/16.0.0/ucd/ (auxiliary/, emoji/ and the top level);
codemirror.js is lib/codemirror.js of codemirror-minified 5.65.9 (node_modules of hydra-editor).
"""
import pathlib
import re
import sys

BREAK_CLASSES = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend", "SpacingMark",
                 "L", "V", "T", "LV", "LVT"]


def read_property(path, wanted=None):
    ranges = []
    for line in pathlib.Path(path).read_text(encoding="utf-8").splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        codepoints, value = [part.strip() for part in line.split(";")[:2]]
        if wanted and value not in wanted:
            continue
        first, _, last = codepoints.partition("..")
        ranges.append((int(first, 16), int(last or first, 16), value))
    return sorted(ranges)


def merge(ranges):
    merged = []
    for first, last, value in ranges:
        if merged and merged[-1][2] == value and merged[-1][1] + 1 == first:
            merged[-1] = (merged[-1][0], last, value)
        else:
            merged.append((first, last, value))
    return merged


def codemirror_extending(path):
    """The character class of extendingChars in CodeMirror 5, without the low surrogates (UTF-8 has none)."""
    source = pathlib.Path(path).read_text(encoding="utf-8")
    body = re.search(r"Ag=/\[(\\u0300[^\]]*)\]/", source).group(1)
    ranges = []
    for match in re.finditer(r"\\u([0-9a-fA-F]{4})(?:-\\u([0-9a-fA-F]{4}))?", body):
        first = int(match.group(1), 16)
        last = int(match.group(2) or match.group(1), 16)
        if 0xDC00 <= first <= 0xDFFF:
            continue
        ranges.append((first, last, "Extend"))
    return merge(sorted(ranges))


def table(name, ranges, with_value=False):
    lines = [f"static const struct unicode_range {name}[] = {{"]
    for first, last, value in ranges:
        value_text = BREAK_CLASSES.index(value) if with_value else 1
        lines.append(f"    {{ 0x{first:X}, 0x{last:X}, {value_text} }},")
    lines.append("};")
    return "\n".join(lines)


def main():
    grapheme, emoji, east_asian, codemirror = sys.argv[1:5]
    # LV and LVT are computed from the Hangul syllable block, so the table leaves them out.
    breaks = merge([r for r in read_property(grapheme) if r[2] not in ("LV", "LVT")])
    pictographic = merge([(a, b, "1") for a, b, _ in read_property(emoji, {"Extended_Pictographic"})])
    presentation = merge([(a, b, "1") for a, b, _ in read_property(emoji, {"Emoji_Presentation"})])
    wide = merge([(a, b, "1") for a, b, _ in read_property(east_asian, {"W", "F"})])
    output = [
        "// Generated by tools/unicode_tables.py from the Unicode Character Database 16.0.0 and the extendingChars of",
        "// CodeMirror 5.65.9. Do not edit.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "struct unicode_range {",
        "    uint32_t first, last;",
        "    uint8_t value;",
        "};",
        "",
        "// Grapheme_Cluster_Break, as enum unicode_break of src/unicode.h; LV and LVT come from the syllable block.",
        table("grapheme_break_ranges", breaks, with_value=True),
        "",
        table("extended_pictographic_ranges", pictographic),
        "",
        "// East_Asian_Width W and F: two columns.",
        table("wide_ranges", wide),
        "",
        "// Emoji_Presentation: shown as emoji without a variation selector.",
        table("emoji_presentation_ranges", presentation),
        "",
        "// The characters that the cursor of CodeMirror 5 never stops before (extendingChars).",
        table("codemirror_extending_ranges", codemirror_extending(codemirror)),
        "",
    ]
    pathlib.Path(__file__).resolve().parent.parent.joinpath("src", "unicode_tables.h").write_text("\n".join(output))


main()
